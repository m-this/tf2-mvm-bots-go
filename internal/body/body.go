/*
Package body lists the Go packages that become SourcePawn bodies.

One list, read by cmd/gen and by the tests that prove the output, so a body
that is generated is a body that is checked. A package under this directory and
not in All is generated by nobody and proved by nobody.
*/
package body

import (
	"fmt"
	"path/filepath"

	"github.com/m-this/tf2-mvm-bots-go/internal/gosubset"
	"github.com/m-this/tf2-mvm-bots-go/internal/spbody"
)

// ExternDir is the one package a body may import: the engine calls, each
// carrying the directive that says how SourcePawn writes it.
const ExternDir = "internal/engine"

// Body is one Go package and the file it becomes.
type Body struct {
	// Dir is the package, relative to the repository root.
	Dir string
	// Out is the generated file, relative to the output directory.
	Out string
	// Hooks is the generated DHook callbacks, relative to the output
	// directory. They are a file of their own because they name SourceMod's
	// DHookParam and MRESReturn, which the standalone SourcePawn the bodies
	// are proved under does not have.
	Hooks string
	// Prefix goes in front of every emitted name. Go_ says at the call site
	// that the function came from here and is not to be edited.
	Prefix string
}

// All is every body. Adding one here is what makes it generated.
var All = []Body{
	{Dir: "internal/body/roster", Out: "sourcepawn/roster.sp", Hooks: "sourcepawn/roster_dhooks.sp", Prefix: "Go_"},
}

// Generate emits every body, keyed by its output path.
func Generate(root string) (map[string][]byte, error) {
	externs, err := spbody.ExternsFromDir(filepath.Join(root, ExternDir))
	if err != nil {
		return nil, err
	}
	out := make(map[string][]byte, len(All))
	for _, b := range All {
		g, err := spbody.GenerateDir(filepath.Join(root, b.Dir), spbody.Config{
			Prefix:  b.Prefix,
			Externs: externs,
		})
		if err != nil {
			return nil, fmt.Errorf("generating %s: %w", b.Dir, err)
		}
		out[b.Out] = []byte(g.Source)
		if g.Hooks == "" {
			continue
		}
		if b.Hooks == "" {
			return nil, fmt.Errorf("%s declares a DHook and names no file to put it in", b.Dir)
		}
		out[b.Hooks] = []byte(g.Hooks)
	}
	return out, nil
}

// SubsetConfig is what gosubset accepts in a body: the extern package, by the
// names it actually declares, and nothing else.
func SubsetConfig(root string) (gosubset.Config, error) {
	externs, err := spbody.ExternsFromDir(filepath.Join(root, ExternDir))
	if err != nil {
		return gosubset.Config{}, err
	}
	cfg := gosubset.DefaultConfig()
	names := make([]string, 0, len(externs))
	for qualified := range externs {
		names = append(names, qualified[len(externPackage)+1:])
	}
	cfg.Packages[modulePath+"/"+ExternDir] = names
	return cfg, nil
}

const (
	modulePath    = "github.com/m-this/tf2-mvm-bots-go"
	externPackage = "engine"
)
